#str start:stop
name = 'Nuttapol'
print('name slicing 0:3:', name[0:3])
print('name slicing 3:7:', name[3:7])
print('name slicing 3:', name[3:])
print('name slicing :7', name[:7])
print('name slicing -1:-4:', name[-1:-4])
print('name slicing : = ', name[:])
#การใช้ slicing เพื่อเข้าถึงตำแหน่งของสตริง
#การใช้ index ของสตริงเริ่มจาก 0
